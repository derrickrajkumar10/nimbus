"""Hit Rate and lead time on the Michaung Replay (#26, cut down). Offline: no AWS.

Runs engines/risk's MichaungScorer over the fixture Segments every 15 minutes of
sim_time, as a Prior-only Run (no Reports, so no Readings), records when each
Segment first reached watch and likely, compares that with the locked news reports
in michaung_reported.json, and writes HIT_RATE.md.

    uv run python hit_rate.py
"""

import json
import sys
from collections.abc import Callable, Sequence
from dataclasses import dataclass
from datetime import datetime, timedelta
from pathlib import Path

from nimbus_contracts.entities import Segment, SegmentRisk

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "engines"))  # engines/ is bundled as-is, not installed

from risk import MichaungScorer  # noqa: E402

RUN = "replay-michaung"
START = datetime.fromisoformat("2023-12-02T12:00:00+05:30")
END = datetime.fromisoformat("2023-12-05T00:00:00+05:30")
STEP = timedelta(minutes=15)
LOCALITY_SHARE = 0.2  # a report counts as predicted when 20% of its Segments reach likely
SEGMENTS = HERE.parent / "contracts" / "fixtures" / "segments.json"
REPORTED = HERE / "michaung_reported.json"
OUTPUT = HERE / "HIT_RATE.md"

Scorer = Callable[[Sequence[Segment], str, datetime], list[SegmentRisk]]


@dataclass
class Crossings:
    watch: datetime | None = None  # first sim_time at watch or higher
    likely: datetime | None = None


@dataclass(frozen=True)
class Result:
    segments: list[Segment]
    crossings: dict[str, Crossings]
    ticks: int
    skipped: int


def load_segments(path: Path = SEGMENTS) -> list[Segment]:
    return [Segment.model_validate(row) for row in json.loads(path.read_text())]


def load_reports(path: Path = REPORTED) -> list[dict]:
    return json.loads(path.read_text())["reports"]


def first_crossings(
    segments: Sequence[Segment],
    scorer: Scorer,
    start: datetime = START,
    end: datetime = END,
    step: timedelta = STEP,
) -> Result:
    crossings = {s.segment_id: Crossings() for s in segments}
    ticks = skipped = 0
    sim_time = start
    while sim_time <= end:
        try:
            risks = scorer(segments, RUN, sim_time)
        except ValueError as error:
            if "rain covers" not in str(error):
                raise
            skipped += 1
        else:
            ticks += 1
            for risk in risks:
                seen = crossings[risk.segment_id]
                if risk.band in ("watch", "likely") and seen.watch is None:
                    seen.watch = sim_time
                if risk.band == "likely" and seen.likely is None:
                    seen.likely = sim_time
        sim_time += step
    return Result(list(segments), crossings, ticks, skipped)


def render(result: Result, reports: Sequence[dict]) -> str:
    report_for = {sid: r for r in reports for sid in r["segment_ids"]}
    likely = [s for s in result.segments if result.crossings[s.segment_id].likely]
    watched = [(c.watch, sid) for sid, c in result.crossings.items() if c.watch]

    rows = []
    for segment in sorted(result.segments, key=lambda s: (_sort_time(result.crossings[s.segment_id].likely), s.segment_id)):
        seen = result.crossings[segment.segment_id]
        report = report_for.get(segment.segment_id)
        reported = datetime.fromisoformat(report["reported_at"]) if report else None
        lead = f"{(reported - seen.likely) / timedelta(hours=1):+.1f}" if reported and seen.likely else "—"
        rows.append(
            f"| {segment.street_name or '(unnamed)'} | `{segment.segment_id}` | {_when(seen.watch)} | "
            f"{_when(seen.likely)} | {_when(reported) if report else '—'} | {lead} |"
        )

    summary = [
        f"- **{len(likely)} of {len(result.segments)}** Segments reached likely.",
        f"- **Earliest watch:** {_earliest(watched, result.segments)}.",
        f"- {result.ticks} ticks scored, {result.skipped} skipped for missing rain.",
    ]
    if reports:
        predicted = [r for r in reports if _predicted(r, result.crossings)]
        reported_ids = set(report_for)
        false_alarms = [s for s in likely if s.segment_id not in reported_ids]
        summary.append(f"- **Hit Rate:** {len(predicted)} of {len(reports)} reports ({len(predicted) / len(reports):.0%}).")
        summary.append(f"- **False alarms:** {len(false_alarms)} Segments reached likely with no report.")
    else:
        summary.append("- **Hit Rate:** no reports locked. `michaung_reported.json` is empty until each source is verified.")

    return "\n".join(
        [
            "# Hit Rate: Michaung Replay",
            "",
            "Generated by `replay/hit_rate.py`. Do not edit by hand.",
            "",
            "## Summary",
            "",
            *summary,
            "",
            "## Segments",
            "",
            "Times are IST. Lead time is hours from first likely to the report; negative means the report came first.",
            "",
            "| Street | Segment | First watch | First likely | Reported | Lead time (h) |",
            "|---|---|---|---|---|---|",
            *rows,
            "",
            "## Method and limits",
            "",
            f"A Prior-only Run (`{RUN}`, no Reports, so no Readings): the F2 risk engine's `MichaungScorer` scores "
            f"each Segment every {STEP // timedelta(minutes=1)} minutes of sim_time from {START:%d %b %H:%M} to "
            f"{END:%d %b %H:%M}, and the first tick at watch (or higher) and at likely is recorded. A report counts "
            f"as predicted when at least {LOCALITY_SHARE:.0%} of its Segments reach likely. Limits: these are the "
            "21 fixture Segments only, not real F1 Segments; the rain is archived Open-Meteo (ERA5) for one grid "
            "cell about 4 km west of Velachery, which underestimates Michaung and is the same for every Segment, "
            "and is treated as a perfect 3-hour forecast; Baseline Thresholds come from fixtures because there is "
            "no terrain model yet (#13); tide is not used.",
            "",
        ]
    )


def _predicted(report: dict, crossings: dict[str, Crossings]) -> bool:
    ids = report["segment_ids"]
    hits = sum(1 for sid in ids if sid in crossings and crossings[sid].likely)
    return bool(ids) and hits / len(ids) >= LOCALITY_SHARE


def _earliest(watched: list[tuple[datetime, str]], segments: Sequence[Segment]) -> str:
    if not watched:
        return "never"
    when, sid = min(watched)
    name = next(s.street_name for s in segments if s.segment_id == sid) or sid
    return f"{_when(when)}, {name} (`{sid}`)"


def _when(t: datetime | None) -> str:
    return f"{t:%d %b %H:%M}" if t else "never"


def _sort_time(t: datetime | None) -> datetime:
    return t or datetime.max.replace(tzinfo=START.tzinfo)


def main() -> int:
    result = first_crossings(load_segments(), MichaungScorer())
    reports = load_reports()
    OUTPUT.write_text(render(result, reports))
    likely = sum(1 for c in result.crossings.values() if c.likely)
    print(f"{likely} of {len(result.segments)} Segments reached likely; wrote {OUTPUT.name}")
    if not reports:
        print("no reports locked")
    return 0


if __name__ == "__main__":
    sys.exit(main())
